"""F-02: P-256 ECDSA Key & Signature Engine Tests.
Validates P-256 (secp256r1) keypair generation, ASN.1 DER signing,
and cryptographic signature verification over SHA-256.
"""

import pytest
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives import hashes, serialization
from tests_e2e.fixtures.crypto_fixtures import (
    generate_p256_keypair,
    sign_p256_der,
    verify_p256_der,
)


class TestF02ECDSAEngine:
    """Verifies P-256 ECDSA cryptographic engine specifications."""

    def test_keypair_curve_and_parameters(self, primary_device_keypair):
        """Test 1: Verifies generated key is on the SECP256R1 curve with 256-bit key size."""
        priv_key, pub_pem, pub_der = primary_device_keypair
        assert isinstance(priv_key.curve, ec.SECP256R1)
        assert priv_key.key_size == 256
        assert "BEGIN PUBLIC KEY" in pub_pem
        assert len(pub_der) > 0

    def test_signature_generation_and_verification(self, primary_device_keypair):
        """Test 2: Verifies valid ASN.1 DER signature verification over SHA-256 of payload."""
        priv_key, pub_pem, _ = primary_device_keypair
        payload = b"PRAMAN-CANONICAL-PAYLOAD-SAMPLE"

        sig = sign_p256_der(priv_key, payload)
        assert len(sig) in range(68, 74)  # Standard P-256 DER length range

        valid = verify_p256_der(pub_pem, sig, payload)
        assert valid is True

    def test_tampered_payload_rejection(self, primary_device_keypair):
        """Test 3: Verifies that even a single-bit flip in payload invalidates the signature."""
        priv_key, pub_pem, _ = primary_device_keypair
        payload = b"ORIGINAL_EVIDENCE_IMAGE_HASH"
        sig = sign_p256_der(priv_key, payload)

        tampered_payload = b"ORIGINAL_EVIDENCE_IMAGE_HASh"
        assert verify_p256_der(pub_pem, sig, tampered_payload) is False

    def test_cross_keypair_rejection(self, primary_device_keypair, secondary_device_keypair):
        """Test 4: Verifies that a signature generated by Key A is rejected by Key B's public key."""
        priv_a, _, _ = primary_device_keypair
        _, pub_b_pem, _ = secondary_device_keypair
        payload = b"AUTHENTIC_FARM_DATA"

        sig_a = sign_p256_der(priv_a, payload)
        assert verify_p256_der(pub_b_pem, sig_a, payload) is False

    def test_tampered_der_signature_rejection(self, primary_device_keypair):
        """Test 5: Verifies that malformed or truncated DER signature bytes are safely rejected."""
        _, pub_pem, _ = primary_device_keypair
        payload = b"DEVICE_ENVELOPE_HASH"

        assert verify_p256_der(pub_pem, b"\x00" * 70, payload) is False
        assert verify_p256_der(pub_pem, b"MALFORMED_NON_DER_STRING", payload) is False
        assert verify_p256_der(pub_pem, b"", payload) is False
